SELECT *
FROM STUDENT AS TABLE1
LEFT JOIN COURSES AS TABLE2
ON TABLE1.STUDENT_ID = TABLE2.STUDENT_ID;   -- > LEFT JOIN  ...

SELECT * 
FROM  STUDENT AS TABLE1
RIGHT JOIN COURSES AS TABLE2 
ON TABLE2.STUDENT_ID = TABLE1.STUDENT_ID;      -- > RIGHT JOIN ....



